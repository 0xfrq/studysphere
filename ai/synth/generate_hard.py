def main():
    planner_rows = []
    rng = random.Random(20261022)
    for index, (device, utterance, task, required, previous) in enumerate(PLANNER_CASES, 1):
        context = context_for(device, rng, previous=previous)
        output = {"task": task, "required_information": canonical_info(required)}
        planner_rows.append(
            make_row(
                f"hard-planner-{index:02d}",
                "planner",
                [
                    {"role": "system", "content": PLANNER_SYSTEM},
                    {"role": "user", "content": user_message(context, utterance)},
                    {"role": "assistant", "content": compact_json(output)},
                ],
                {
                    "profile": "hard",
                    "template": "hard",
                    "language": "id",
                    "device": device,
                    "split": "test",
                    "gold_cost": info_cost(required),
                    "hard": True,
                },
            )
        )

    responder_rows = []
    for case in RESPONDER_CASES:
        facts = dict(case["facts"])
        system = build_system_prompt(case["device"], facts, case["meta"], case.get("missing", {}))
        responder_rows.append(
            make_row(
                f"hard-responder-{case['id']}",
                "responder",
                [
                    {"role": "system", "content": system},
                    {"role": "user", "content": case["user"]},
                ],
                {
                    "intent": case["id"],
                    "template": "hard",
                    "language": "id",
                    "device": case["device"],
                    "split": "test",
                    "state": "hard",
                    "online": case["meta"]["online"],
                    "expect": case["expect"],
                    "hard": True,
                },
            )
        )

    count_planner = write_jsonl(DATA / "eval" / "planner_hard.jsonl", planner_rows)
    count_responder = write_jsonl(DATA / "eval" / "responder_hard.jsonl", responder_rows)
    print(f"eval/planner_hard.jsonl: {count_planner} rows")
    print(f"eval/responder_hard.jsonl: {count_responder} rows")


if __name__ == "__main__":
    main()
